package.path = "./tests/?.lua;" .. package.path
local H = require("harness")
local ns = {}
H.load("DontDoThat/Model/SpecInference.lua", ns)
local S = ns.SpecInference
local hunter = { specs = { BM = { tree = 1, role = "dps" }, MM = { tree = 2, role = "dps" }, SV = { tree = 3, role = "dps" } } }
local pal = { specs = { HOLY = { tree = 1, role = "healer" }, PROT = { tree = 2, role = "tank" }, RET = { tree = 3, role = "dps" } } }
local ALL = { "BM", "MM", "SV" }

test("clear specialization", function() eq(S.Infer(hunter, { { BM = 21 } }), { "BM" }) end)
test("no points -> all", function() eq(S.Infer(hunter, { { BM = 0, MM = 0, SV = 0 } }), ALL) end)
test("empty set list -> all", function() eq(S.Infer(hunter, {}), ALL) end)
test("near-even split keeps both (all)", function()
  local r = S.Infer(hunter, { { BM = 8, MM = 7 } })
  eq(r, ALL)
end)
test("lead below margin: extra point does not change set", function()
  eq(S.Infer(hunter, { { BM = 8, MM = 7 } }), S.Infer(hunter, { { BM = 9, MM = 7 } }))
end)
test("lead at margin narrows", function() eq(S.Infer(hunter, { { BM = 12, MM = 7 } }), { "BM" }) end)
test("configurable margin", function()
  eq(S.Infer(hunter, { { BM = 9, MM = 7 } }, { leadMargin = 2 }), { "BM" })
end)
test("hysteresis keeps narrowed spec above release margin", function()
  eq(S.Infer(hunter, { { BM = 10, MM = 7 } }, { previous = { "BM" } }), { "BM" })
  eq(S.Infer(hunter, { { BM = 10, MM = 7 } }), ALL)
  eq(S.Infer(hunter, { { BM = 8, MM = 7 } }, { previous = { "BM" } }), ALL)
end)
test("dual spec union", function()
  eq(S.Infer(hunter, { { BM = 20 }, { MM = 20 } }), { "BM", "MM" })
end)
test("dual spec with one unspent set -> all", function()
  eq(S.Infer(hunter, { { BM = 20 }, {} }), ALL)
end)
test("depth", function()
  eq(S.Depth({ BM = 15 }, "BM"), 15)
  eq(S.Depth({ BM = 15 }, "MM"), 0)
  truthy(S.Depth({ BM = 15 }, "BM") >= 10)
  falsy(S.Depth({ BM = 5 }, "BM") >= 10)
end)
test("role", function()
  eq(S.Role(pal, { PROT = 20 }), "tank")
  eq(S.Role(pal, { HOLY = 0 }), nil)
  eq(S.Role(hunter, {}), "dps")
  eq(S.Role({ specs = { A = { tree = 1 } } }, { A = 5 }), nil)
end)
