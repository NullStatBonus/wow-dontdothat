package.path = "./tests/?.lua;" .. package.path
local H = require("harness")
local ns = {}
H.load("DontDoThat/Model/SpecInference.lua", ns)
local S = ns.SpecInference
local classData = { specs = { A = { tree = 1, role = "dps" }, B = { tree = 2, role = "dps" }, C = { tree = 3, role = "dps" } } }
local pal = { specs = { HOLY = { tree = 1, role = "healer" }, PROT = { tree = 2, role = "tank" }, RET = { tree = 3, role = "dps" } } }
local ALL = { "A", "B", "C" }

test("clear specialization", function() eq(S.Infer(classData, { { A = 21 } }), { "A" }) end)
test("no points -> all", function() eq(S.Infer(classData, { { A = 0, B = 0, C = 0 } }), ALL) end)
test("empty set list -> all", function() eq(S.Infer(classData, {}), ALL) end)
test("near-even split keeps both (all)", function()
  local r = S.Infer(classData, { { A = 8, B = 7 } })
  eq(r, ALL)
end)
test("lead below margin: extra point does not change set", function()
  eq(S.Infer(classData, { { A = 8, B = 7 } }), S.Infer(classData, { { A = 9, B = 7 } }))
end)
test("lead at margin narrows", function() eq(S.Infer(classData, { { A = 12, B = 7 } }), { "A" }) end)
test("configurable margin", function()
  eq(S.Infer(classData, { { A = 9, B = 7 } }, { leadMargin = 2 }), { "A" })
end)
test("hysteresis keeps narrowed spec above release margin", function()
  eq(S.Infer(classData, { { A = 10, B = 7 } }, { previous = { "A" } }), { "A" })
  eq(S.Infer(classData, { { A = 10, B = 7 } }), ALL)
  eq(S.Infer(classData, { { A = 8, B = 7 } }, { previous = { "A" } }), ALL)
end)
test("dual spec union", function()
  eq(S.Infer(classData, { { A = 20 }, { B = 20 } }), { "A", "B" })
end)
test("dual spec with one unspent set -> all", function()
  eq(S.Infer(classData, { { A = 20 }, {} }), ALL)
end)
test("depth", function()
  eq(S.Depth({ A = 15 }, "A"), 15)
  eq(S.Depth({ A = 15 }, "B"), 0)
  truthy(S.Depth({ A = 15 }, "A") >= 10)
  falsy(S.Depth({ A = 5 }, "A") >= 10)
end)
test("role", function()
  eq(S.Role(pal, { PROT = 20 }), "tank")
  eq(S.Role(pal, { HOLY = 0 }), nil)
  eq(S.Role(classData, {}), "dps")
  eq(S.Role({ specs = { A = { tree = 1 } } }, { A = 5 }), nil)
end)
