#!/usr/bin/env python3
"""Builds DontDoThat/Data/TrainerPrices.lua: what each class trainer charges per spell, in copper.

Source: Wowhead's Classic spell lists (https://www.wowhead.com/classic/spells/abilities/<class>), whose rows carry
a "trainingcost". The game's data files do not hold trainer prices. Wowhead's prices matched every one of the
106 Hunter prices seen at a real trainer, so they stand in for the other classes until a trainer is exported.
Only spells in Data/SpellData.lua (by ID, or an alternate ID) are written.

Usage (from the repo root):
    python3 tools/fetch-trainer-prices.py [--cache tools/.cache] [--out DontDoThat/Data/TrainerPrices.lua]

Downloaded pages are untrusted data: they are only parsed as text here, never run.
"""
import argparse
import json
import os
import re
import urllib.request

CLASSES = {"WARRIOR": "warrior", "PALADIN": "paladin", "HUNTER": "hunter", "ROGUE": "rogue", "PRIEST": "priest",
           "SHAMAN": "shaman", "MAGE": "mage", "WARLOCK": "warlock", "DRUID": "druid"}


def page(cache, slug):
    path = os.path.join(cache, f"wowhead-{slug}.html")
    if not os.path.exists(path):
        req = urllib.request.Request(f"https://www.wowhead.com/classic/spells/abilities/{slug}",
                                     headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=90) as resp, open(path, "wb") as f:
            f.write(resp.read())
    return open(path, encoding="utf-8", errors="replace").read()


def priced(html):
    m = re.search(r"var listviewspells = (\[.*?\]);\s*\n", html, re.S)
    if not m:
        raise SystemExit("no spell list in the page; Wowhead's layout changed")
    rows = json.loads(re.sub(r"(?<=[{,])([a-z]+):", r'"\1":', m.group(1)))
    return {r["id"]: r["trainingcost"] for r in rows if r.get("trainingcost")}


def our_ids(spell_data):
    out = {}
    parts = re.split(r"\n  ([A-Z]+) = \{", spell_data)
    for i in range(1, len(parts), 2):
        rows = []
        for m in re.finditer(r"id = (\d+),[^\n]*?(?:alt = \{([^}]*)\})?\s*\},?\n", parts[i + 1]):
            ids = [int(m.group(1))] + [int(x) for x in re.findall(r"\d+", m.group(2) or "")]
            rows.append(ids)
        out[parts[i]] = rows
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default="tools/.cache")
    ap.add_argument("--out", default="DontDoThat/Data/TrainerPrices.lua")
    args = ap.parse_args()
    os.makedirs(args.cache, exist_ok=True)
    ours = our_ids(open("DontDoThat/Data/SpellData.lua", encoding="utf-8").read())
    lines = ["local addonName, ns = ...", "",
             "-- GENERATED by tools/fetch-trainer-prices.py. Do not edit by hand; re-run the script.",
             "-- What a class trainer charges per spell, in copper, from Wowhead's Classic spell lists.",
             "-- Not confirmed at your own trainer: prices seen there (Tally) take precedence.",
             "ns.TrainerPrices = {"]
    for key, slug in CLASSES.items():
        prices = priced(page(args.cache, slug))
        entries = {}
        for ids in ours.get(key, []):
            for sid in ids:
                if sid in prices:
                    entries[ids[0]] = prices[sid]
                    break
        lines.append(f"  {key} = {{")
        row = []
        for sid in sorted(entries):
            row.append(f"[{sid}] = {entries[sid]}")
            if len(row) == 8:
                lines.append("    " + ", ".join(row) + ","); row = []
        if row:
            lines.append("    " + ", ".join(row) + ",")
        lines.append("  },")
        print(f"{key}: {len(entries)} of {len(ours.get(key, []))} spells priced")
    lines += ["}", ""]
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
