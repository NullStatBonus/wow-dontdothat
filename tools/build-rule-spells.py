#!/usr/bin/env python3
"""Builds DontDoThat/Data/RuleSpells.lua: the spells the rule files name that the trainer-based tables in
Data/SpellData.lua do not list (talent-granted spells, default attacks, conjured items, passives).

Rule files are written with English spell names and resolved to spell IDs at load, so every name must have an
ID. tests/spell_ids_test.lua fails on a name with none; add it to tools/rule-spell-names.txt ("CLASS<TAB>Name")
and run this again. A name gets every ID it has in the class's skill-line abilities and in its talent ranks, in both
the Classic Era and the Forever build, so a talent link and a trainer row reach the same family.
Rows get kind = "other" and no price, so they never count as purchases.

Usage:
    tools/build-rule-spells.py [--build 1.60.1.70532] [--era-build 1.15.9.70003] [--cache DIR] [--names FILE] [--out FILE]
"""
import argparse
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("build_spell_data", os.path.join(HERE, "build-spell-data.py"))
bsd = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bsd)

MASKS = {"WARRIOR": 1, "PALADIN": 2, "HUNTER": 4, "ROGUE": 8, "PRIEST": 16, "SHAMAN": 64, "MAGE": 128,
         "WARLOCK": 256, "DRUID": 1024}


def read_names(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line and not line.startswith("#"):
            cls, name = line.split("\t", 1)
            out.setdefault(cls, []).append(name)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", help="Forever build; the newest when omitted")
    ap.add_argument("--era-build", default="1.15.9.70003")
    ap.add_argument("--cache", default=os.path.join(HERE, ".cache"))
    ap.add_argument("--names", default=os.path.join(HERE, "rule-spell-names.txt"))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "DontDoThat", "Data", "RuleSpells.lua"))
    args = ap.parse_args()
    builds = [args.era_build, args.build or bsd.newest_forever_build()]

    # The rule files are written with Classic Era names and the bundled tables come from Forever, which renamed
    # some spells under the same ID (Curse of Agony is Bane of Agony). Look a name up in both builds.
    def load(build):
        t = {name: bsd.fetch(name, build, args.cache)
             for name in ("SpellName", "Spell", "SpellLevels", "SkillLineAbility", "Talent", "TalentTab")}
        d = {"names": {r["ID"]: r["Name_lang"] for r in t["SpellName"]}, "t": t}
        d["by_name"] = {}
        for sid, n in d["names"].items():
            d["by_name"].setdefault(n, set()).add(sid)
        d["subtext"] = {r["ID"]: r["NameSubtext_lang"] for r in t["Spell"]}
        d["levels"] = {r["SpellID"]: r for r in t["SpellLevels"]}
        d["tab_mask"] = {r["ID"]: int(r["ClassMask"] or 0) for r in t["TalentTab"]}
        return d

    data = [load(b) for b in builds]

    def rank_of(d, sid):
        m = re.search(r"(\d+)", d["subtext"].get(sid, "") or "")
        return int(m.group(1)) if m else None

    def level_of(d, sid):
        r = d["levels"].get(sid)
        return (int(r["SpellLevel"]) or int(r["BaseLevel"]) or 0) if r else 0

    wanted = read_names(args.names)
    out, missing = ["-- GENERATED by tools/build-rule-spells.py. Do not edit by hand; re-run the script.",
                    "-- Spells the rule files name that Data/SpellData.lua does not list under that name. Builds "
                    + ", ".join(builds) + ".",
                    "local addonName, ns = ...", "", "ns.RuleSpells = {"], []
    for cls in sorted(wanted):
        mask = MASKS[cls]
        pools = []
        for d in data:
            ability_ids = {r["Spell"] for r in d["t"]["SkillLineAbility"] if int(r["ClassMask"] or 0) & mask}
            talent_ids = set()
            for r in d["t"]["Talent"]:
                if d["tab_mask"].get(r["TabID"], 0) & mask:
                    talent_ids.update(r[f"SpellRank_{i}"] for i in range(9) if r[f"SpellRank_{i}"] not in ("", "0"))
            pools.append((d, ability_ids, talent_ids))
        rows = {}
        for name in sorted(set(wanted[cls])):
            # Every ID the name has in the class's skill lines AND in its talents, in both builds: a talent's own rank
            # spell (Holy Shock 20473, Era's Feral Charge 16979) is often not a skill-line ability, and the player's
            # talent link leads to it, so it must belong to the same family as the rest.
            found = False
            for d, ability_ids, talent_ids in pools:
                for sid in sorted(d["by_name"].get(name, ()), key=int):
                    if (sid in ability_ids or sid in talent_ids) and (int(sid), name) not in rows:
                        rows[(int(sid), name)] = (rank_of(d, sid), level_of(d, sid))
                        found = True
            if not found:
                missing.append(f"{cls}: {name}")
        out.append(f"  {cls} = {{")
        for (sid, name), (rank, level) in sorted(rows.items(), key=lambda kv: (kv[0][1], kv[0][0])):
            parts = [f"id = {sid}", f"name = {bsd.lua_string(name)}"]
            if rank is not None:
                parts.append(f"rank = {rank}")
            parts += [f"level = {level}", 'kind = "other"']
            out.append("    { " + ", ".join(parts) + " },")
        out.append("  },")
    out.append("}")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {args.out}")
    if missing:
        print("no ID found for:\n  " + "\n  ".join(missing), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
