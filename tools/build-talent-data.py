#!/usr/bin/env python3
"""Builds DontDoThat/Data/TalentData.lua: for every talent, the spell IDs of its ranks.

The client's talent hyperlink (GetTalentLink) carries the talent's database ID, so the addon can tell which talents
a player has without reading any text: talent ID -> rank spell IDs -> spell family. Classic Era and Forever share
talent IDs; both builds are read and a talent that differs between them is listed under both.

Usage:
    tools/build-talent-data.py [--build 1.60.1.70532] [--era-build 1.15.9.70003] [--cache DIR] [--out FILE]
"""
import argparse
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("build_spell_data", os.path.join(HERE, "build-spell-data.py"))
bsd = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bsd)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", help="Forever build; the newest when omitted")
    ap.add_argument("--era-build", default="1.15.9.70003")
    ap.add_argument("--cache", default=os.path.join(HERE, ".cache"))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "DontDoThat", "Data", "TalentData.lua"))
    args = ap.parse_args()
    builds = [args.era_build, args.build or bsd.newest_forever_build()]

    talents = {}
    for build in builds:
        tabs = {r["ID"]: int(r["ClassMask"] or 0) for r in bsd.fetch("TalentTab", build, args.cache)}
        for r in bsd.fetch("Talent", build, args.cache):
            if not tabs.get(r["TabID"], 0):
                continue
            ranks = []
            for i in range(9):
                sid = r[f"SpellRank_{i}"]
                if sid in ("", "0"):
                    break
                ranks.append(int(sid))
            if ranks:
                talents.setdefault(int(r["ID"]), set()).add(tuple(ranks))

    out = ["-- GENERATED by tools/build-talent-data.py. Do not edit by hand; re-run the script.",
           "-- Talent ID (the number in a talent hyperlink) -> the spell IDs of its ranks. Builds " + ", ".join(builds) + ".",
           "local addonName, ns = ...", "", "ns.TalentSpells = {"]
    for tid in sorted(talents):
        variants = sorted(talents[tid])
        ranks = variants[0]
        out.append(f"  [{tid}] = {{ " + ", ".join(str(s) for s in ranks) + " },")
        if len(variants) > 1:
            print(f"talent {tid} differs between builds; kept {ranks}")
    out.append("}")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {len(talents)} talents to {args.out}")


if __name__ == "__main__":
    main()
