#!/usr/bin/env python3
"""Builds DontDoThat/Data/RuleItems.lua: the items the rule files warn about by family, as item ID -> family.

Today that is the Warlock's demon grimoires ("Grimoire of Firebolt (Rank 3)" is family "Firebolt"). The addon reads
the item ID from the item link, so a grimoire is recognised in any client language. Rule files keep authoring the
English family names they want to keep (Rules/Data/Warlock.lua `grimoires.keep`); tests/grimoires_test.lua fails
on a name here that no item has.

The item tables are big downloads, so they go in their own directory, tools/.cache/items, and are read as data.

Usage:
    python3 -I tools/build-rule-items.py [--build 1.60.1.70532] [--era-build 1.15.9.70003] [--cache DIR] [--out FILE]
"""
import argparse
import importlib.util
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("build_spell_data", os.path.join(HERE, "build-spell-data.py"))
bsd = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bsd)

GRIMOIRE = re.compile(r"^Grimoire of (.+?)(?:\s*\(Rank \d+\))?$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", help="Forever build; the newest when omitted")
    ap.add_argument("--era-build", default="1.15.9.70003")
    ap.add_argument("--cache", default=os.path.join(HERE, ".cache", "items"))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "DontDoThat", "Data", "RuleItems.lua"))
    args = ap.parse_args()
    os.makedirs(args.cache, exist_ok=True)
    builds = [args.era_build, args.build or bsd.newest_forever_build()]

    grimoires = {}
    for build in builds:  # the later (Forever) name wins for an ID both builds list
        for r in bsd.fetch("ItemSparse", build, args.cache):
            m = GRIMOIRE.match(r["Display_lang"])
            if m:
                grimoires[int(r["ID"])] = m.group(1)

    out = ["-- GENERATED by tools/build-rule-items.py. Do not edit by hand; re-run the script.",
           "-- Items the rule files warn about by family: item ID -> family. Builds " + ", ".join(builds) + ".",
           "local addonName, ns = ...", "", "ns.RuleItems = {", "  WARLOCK = {"]
    for item_id in sorted(grimoires):
        out.append(f"    [{item_id}] = {bsd.lua_string(grimoires[item_id])},")
    out += ["  },", "}"]
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {len(grimoires)} grimoires in {len(set(grimoires.values()))} families to {args.out}")


if __name__ == "__main__":
    main()
